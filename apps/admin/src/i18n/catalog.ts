import "server-only";
import type { AppLocale } from "@/i18n/config";
import { mergeMessages, type Messages, type MessageTree } from "@/i18n/translate";
import manifest from "./client-namespaces.json";

/**
 * Message catalogs of this app (server only). No `next/root-params` here, so route handlers can use it too;
 * page code goes through ./server.ts.
 */
const loaders: Record<AppLocale, () => Promise<Messages>> = {
  "en-US": () => import("./messages/en-US.json").then((m) => m.default),
  "hi-IN": () => import("./messages/hi-IN.json").then((m) => m.default as Messages),
  "ar-AE": () => import("./messages/ar-AE.json").then((m) => m.default as Messages),
  "de-DE": () => import("./messages/de-DE.json").then((m) => m.default as Messages),
  "zh-CN": () => import("./messages/zh-CN.json").then((m) => m.default as Messages),
};

export function getMessages(locale: AppLocale): Promise<Messages> {
  return loaders[locale]();
}

/** `own` with every message it lacks taken from `fallback` (en-US), so the client never needs the en-US catalog. */
function withFallback(own: unknown, fallback: unknown): unknown {
  if (own === undefined) return fallback;
  if (!own || typeof own !== "object" || !fallback || typeof fallback !== "object") return own;
  const out: Record<string, unknown> = { ...(fallback as Record<string, unknown>) };
  for (const [k, v] of Object.entries(own as Record<string, unknown>)) out[k] = withFallback(v, out[k]);
  return out;
}

const filled = new Map<string, unknown>();

/** One top-level namespace of a locale's catalog (en-US filled in), or undefined if the namespace does not exist. */
export async function getNamespace(locale: AppLocale, ns: string): Promise<unknown> {
  const en = (await getMessages("en-US")) as MessageTree;
  if (!Object.hasOwn(en, ns)) return undefined;
  if (locale === "en-US") return en[ns];
  const key = `${locale}|${ns}`;
  if (!filled.has(key)) filled.set(key, withFallback(((await getMessages(locale)) as MessageTree)[ns], en[ns]));
  return filled.get(key);
}

/**
 * The part of one namespace a manifest unit selects: "ns" (all of it), "ns.*" (its direct string messages) or
 * "ns.sub" (one subtree or message; keys that themselves contain dots, like "agents.max", are matched by prefix),
 * or a deeper path to one message.
 * Mirrors pickUnit in scripts/i18n-namespaces.mjs.
 */
function pickUnit(node: unknown, sub: string | null): unknown {
  if (sub === null) return node;
  if (!node || typeof node !== "object") return undefined;
  const entries = Object.entries(node as Record<string, unknown>);
  if (sub === "*") return Object.fromEntries(entries.filter(([, v]) => typeof v === "string"));
  if (sub in (node as object)) return { [sub]: (node as Record<string, unknown>)[sub] };
  const dotted = entries.filter(([k]) => k.startsWith(`${sub}.`));
  if (dotted.length) return Object.fromEntries(dotted);
  // A deeper path ("reasons.crm_attachment_too_large": one message of a lazy subtree).
  const first = sub.slice(0, sub.indexOf("."));
  const child = first ? (node as Record<string, unknown>)[first] : undefined;
  if (!child || typeof child !== "object") return undefined;
  const inner = pickUnit(child, sub.slice(first.length + 1));
  return inner === undefined ? undefined : { [first]: inner };
}

/**
 * Client message scopes: layouts that render <ClientMessages scope="…"> (and the root layout), mapped to the
 * message units their subtree's client components use beyond what enclosing scopes already provide. Generated by
 * scripts/i18n-namespaces.mjs (`pnpm i18n:sync`); `pnpm i18n:check` fails when it is stale.
 */
const SCOPES: Record<string, string[]> = manifest.scopes;

/** Subtrees never inlined into HTML (see LAZY in scripts/i18n-namespaces.mjs); the client loads them after hydration. */
export const LAZY_UNITS: string[] = manifest.lazy;
const subsets = new Map<string, Promise<MessageTree>>();

/** The messages a client-message scope ships to the browser (memoized per locale and scope). */
export function getScopeMessages(locale: AppLocale, scope: string): Promise<MessageTree> {
  const units = SCOPES[scope];
  if (!units) {
    const msg = `Unknown client message scope "${scope}" — run \`pnpm i18n:sync\` (scripts/i18n-namespaces.mjs).`;
    if (process.env.NODE_ENV !== "production") throw new Error(msg);
    console.error(msg);
    return Promise.resolve({});
  }
  const key = `${locale}|${scope}`;
  let subset = subsets.get(key);
  if (!subset) {
    subset = (async () => {
      let out: unknown = {};
      for (const unit of units) {
        const dot = unit.indexOf(".");
        const ns = dot < 0 ? unit : unit.slice(0, dot);
        const part = pickUnit(await getNamespace(locale, ns), dot < 0 ? null : unit.slice(dot + 1));
        if (part !== undefined) out = mergeMessages(out, { [ns]: part });
      }
      return out as MessageTree;
    })();
    subsets.set(key, subset);
  }
  return subset;
}
